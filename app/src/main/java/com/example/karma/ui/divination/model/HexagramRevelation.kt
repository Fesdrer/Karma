/**
 * 八卦（三画卦），按伏羲先天序编号
 * 数值：坤0 艮1 坎2 巽3 震4 离5 兑6 乾7
 * 五行：乾兑金、离火、震巽木、坎水、艮坤土
 */
enum class Trigram(val value: Int, val label: String, val element: String, val unicode: String) {
    KUN(0, "坤", "土", "☷"),   // ☷
    GEN(1, "艮", "土", "☶"),   // ☶
    KAN(2, "坎", "水", "☵"),   // ☵
    XUN(3, "巽", "木", "☴"),   // ☴
    ZHEN(4, "震", "木", "☳"),  // ☳
    LI(5, "离", "火", "☲"),    // ☲
    DUI(6, "兑", "金", "☱"),   // ☱
    QIAN(7, "乾", "金", "☰");  // ☰

    companion object {
        /** 从伏羲数值 0-7 映射到枚举 */
        private val map = entries.associateBy { it.value }
        fun fromValue(v: Int): Trigram = map[v]!!

        // 爻画二进制（阳=1, 阴=0, bit0=初爻）→ 伏羲先天序值
        // 震 binary=0b001=1 ↔ 伏羲序4，兑 binary=0b011=3 ↔ 伏羲序6
        // 艮 binary=0b100=4 ↔ 伏羲序1，巽 binary=0b110=6 ↔ 伏羲序3
        private val yaoToXianTian = intArrayOf(0, 4, 2, 6, 1, 5, 3, 7)
        private val xianTianToYao = intArrayOf(0, 4, 2, 6, 1, 5, 3, 7)

        /** 爻画二进制值 → 伏羲先天序值 */
        fun yaoBinaryToValue(b: Int): Int = yaoToXianTian[b and 7]

        /** 伏羲先天序值 → 爻画二进制值 */
        fun valueToYaoBinary(v: Int): Int = xianTianToYao[v and 7]
    }
}

/**
 * 一卦的完整启示数据
 * @param name 卦名，如"泰"
 * @param fullName 完整卦名，如"地天泰"
 * @param summary 卦象总纲，只讲气场和态势
 * @param prosperity 盛衰系数 -10..+10
 * @param trend 趋势属性：上升/下降/震荡/平稳
 * @param lowerTrigram 下卦（内卦）
 * @param upperTrigram 上卦（外卦）
 * @param revelations 六爻启示[6]，从初爻到上爻
 */
data class HexagramRevelation(
    val name: String,
    val fullName: String,
    val summary: String,
    val prosperity: Int,
    val trend: String,
    val lowerTrigram: Trigram,
    val upperTrigram: Trigram,
    val revelations: List<String>,
)

/** 合解引擎计算结果 */
data class IntegrationResult(
    val energyFlow: String,    // 能量流向
    val trendDesc: String,     // 趋势描述
    val diff: Int,             // 差值
)

// ==================== 五行生克工具 ====================

private val elementCycle = listOf("金", "水", "木", "火", "土")

/** 五行生：A是否生B */
private fun generates(a: String, b: String): Boolean {
    val ai = elementCycle.indexOf(a)
    val bi = elementCycle.indexOf(b)
    if (ai == -1 || bi == -1) return false
    return (ai + 1) % 5 == bi
}

/** 五行克：A是否克B */
private fun controls(a: String, b: String): Boolean {
    val ai = elementCycle.indexOf(a)
    val bi = elementCycle.indexOf(b)
    if (ai == -1 || bi == -1) return false
    return (ai + 2) % 5 == bi
}

// ==================== 合解引擎 ====================

object IntegrationEngine {

    /**
     * 体用生克 + 趋势演算
     * 体五行 = 主卦.下卦五行
     * 用五行 = 变卦.上卦五行
     */
    fun calculate(
        primary: HexagramRevelation,
        transformed: HexagramRevelation,
    ): IntegrationResult {
        // 体用生克
        val bodyElem = primary.lowerTrigram.element   // 体五行
        val useElem = transformed.upperTrigram.element // 用五行

        val energyFlow = when {
            generates(useElem, bodyElem) -> "外力助我"
            controls(useElem, bodyElem) -> "外力制我"
            generates(bodyElem, useElem) -> "我在付出"
            controls(bodyElem, useElem) -> "我在掌控"
            else -> "内外同步"
        }

        // 趋势演算
        val diff = transformed.prosperity - primary.prosperity
        val trendDesc = when {
            diff >= 5 -> "大幅好转，由阴转阳"
            diff >= 1 -> "缓慢上升，渐入佳境"
            diff == 0 -> "维持原状，以静制动"
            diff > -5 -> "缓慢下滑，小有损耗"
            else -> "急转直下，由盛转衰"
        }

        return IntegrationResult(
            energyFlow = energyFlow,
            trendDesc = trendDesc,
            diff = diff,
        )
    }
}

// ==================== 卦库工具 ====================

object HexagramLibrary {

    /** 按伏羲序（下卦*8+上卦）索引。null 表示未加载，调用 ensureLoaded() 后填充 */
    @Volatile
    private var hexagrams: Array<HexagramRevelation>? = null

    /** 确保卦库已加载（幂等，线程安全）。在占卜开始时调用。 */
    fun ensureLoaded() {
        if (hexagrams == null) {
            synchronized(this) {
                if (hexagrams == null) {
                    hexagrams = initHexagrams()
                }
            }
        }
    }

    /** 释放卦库内存。在占卜结束后调用。 */
    fun release() {
        synchronized(this) {
            hexagrams = null
        }
    }

    private fun loaded(): Array<HexagramRevelation> =
        hexagrams ?: throw IllegalStateException("HexagramLibrary not loaded, call ensureLoaded() first")

    /**
     * 从六爻二进制值获取卦象
     * @param binaryValue 0-63，从下到上：bit0=初爻  ... bit5=上爻（1为阳，0为阴）
     *                    低3位=下卦值，高3位=上卦值，数据按 下卦*8+上卦 索引
     */
    fun getByBinary(binaryValue: Int): HexagramRevelation {
        require(binaryValue in 0..63)
        // 爻画二进制 → 伏羲先天序值（巽3/震4 映射与非映射不同）
        val lowerBin = binaryValue and 0b111               // bits 0-2
        val upperBin = (binaryValue shr 3) and 0b111        // bits 3-5
        val lower = Trigram.yaoBinaryToValue(lowerBin)      // 伏羲序
        val upper = Trigram.yaoBinaryToValue(upperBin)      // 伏羲序
        return loaded()[lower * 8 + upper]
    }

    /** 从六条阴阳爻获取卦象 */
    fun fromLines(lines: List<Boolean>): HexagramRevelation {
        require(lines.size == 6)
        var binary = 0
        for (i in 0..5) {
            if (lines[i]) binary = binary or (1 shl i)
        }
        return getByBinary(binary)
    }

    /** 从六条 HexagramLine 获取卦象 */
    fun fromHexagramLines(lines: List<HexagramLine>): HexagramRevelation {
        return fromLines(lines.map { it.isYang })
    }

